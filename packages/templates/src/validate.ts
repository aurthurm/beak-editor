/**
 * Validation of a document against its template (roadmap 5F rules).
 *
 * The editor runs this as feedback. The server runs it as the authoritative check.
 * Pure functions, no DOM.
 *
 * @module
 */

import type { Block } from '@amusendame/beakblock-core';
import type { BeakDocument, DocumentProperties } from '@amusendame/beakblock-schema';

import { contentHash } from './hash';
import { findBlocks } from './blocks';
import { flattenBlocks } from './authoring';
import type { FieldRules, TemplateDefinition, TemplateSectionDefinition, ValidationIssue } from './types';

/** Block types that count as procedure steps for `kind: 'procedure'` sections. */
export const DEFAULT_PROCEDURE_BLOCK_TYPES: readonly string[] = ['procedureStep', 'sopStep'];

/** A block-level validator, such as `BlockRegistry` from core. */
export interface BlockValidator {
  validate(blocks: Block[]): Array<{ severity: 'error' | 'warning' | 'info'; code: string; message: string; blockId?: string }>;
}

/** Options for {@link validateAgainstTemplate}. */
export interface ValidateOptions {
  /** Overrides the template's property rules. */
  fieldRules?: FieldRules;
  /** True when the caller is the approval workflow (allows the workflow-only effective date). */
  fromWorkflow?: boolean;
  /** Block-level validation through the block registry. Issues are passed through. */
  registry?: BlockValidator;
  /** Block types that count as procedure steps. */
  procedureBlockTypes?: readonly string[];
}

/** Validates document properties against property rules. Synchronous. */
export function validateProperties(
  properties: DocumentProperties,
  rules: FieldRules,
  options: { fromWorkflow?: boolean } = {}
): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const record = properties as unknown as Record<string, unknown>;
  for (const [name, rule] of Object.entries(rules)) {
    const raw = name === 'custom' ? undefined : record[name];
    const value = raw === undefined || raw === null ? '' : String(raw);
    if (rule.generated && value.trim() === '') {
      issues.push({ severity: 'error', code: 'property-generated-missing', message: `Property "${name}" is generated by the QMS service and is missing` });
      continue;
    }
    if (rule.required && value.trim() === '') {
      issues.push({ severity: 'error', code: 'property-required', message: `Property "${name}" is required` });
      continue;
    }
    if (value === '') continue;
    if (rule.maxLength !== undefined && value.length > rule.maxLength) {
      issues.push({
        severity: 'error',
        code: 'property-too-long',
        message: `Property "${name}" is longer than ${rule.maxLength} characters`,
      });
    }
    if (rule.pattern !== undefined && !new RegExp(rule.pattern).test(value)) {
      issues.push({ severity: 'error', code: 'property-pattern', message: `Property "${name}" does not match ${rule.pattern}` });
    }
    if (rule.source === 'workflow' && !options.fromWorkflow) {
      issues.push({
        severity: 'error',
        code: 'property-workflow-only',
        message: `Property "${name}" is set by the approval workflow, not by authors`,
      });
    }
  }
  return issues;
}

/** Strips ids and marker props so boilerplate compares by content. */
function normaliseBoilerplate(blocks: readonly Block[]): unknown {
  return blocks.map((block) => {
    const props = { ...(block.props ?? {}) } as Record<string, unknown>;
    delete props.lockedBy;
    delete props.templateSectionId;
    delete props.placeholder;
    const out: Record<string, unknown> = { type: block.type, props, content: block.content };
    if (block.children) out.children = normaliseBoilerplate(block.children);
    return out;
  });
}

/** Locked boilerplate in the section, in order (blocks marked `lockedBy: 'template'`). */
function boilerplateIn(section: Block): Block[] {
  return (section.children ?? []).filter((c) => (c.props as Record<string, unknown>)?.lockedBy === 'template');
}

async function checkSection(
  def: TemplateSectionDefinition,
  section: Block,
  procedureTypes: readonly string[]
): Promise<ValidationIssue[]> {
  const issues: ValidationIssue[] = [];
  const at = { sectionId: String((section.props as Record<string, unknown>).sectionId ?? ''), templateSectionId: def.templateSectionId };
  const children = section.children ?? [];
  const allowed = def.allowedBlocks !== undefined ? def.allowedBlocks : ((section.props as Record<string, unknown>).allowedBlocks as string[] | null);

  if (Array.isArray(allowed)) {
    for (const child of children) {
      if (!allowed.includes(child.type)) {
        issues.push({ ...at, severity: 'error', code: 'disallowed-block', message: `Block type "${child.type}" is not allowed in "${def.title}"`, blockId: child.id });
      }
    }
  }

  const real = children.filter((c) => (c.props as Record<string, unknown>)?.placeholder !== true);
  if (def.minBlocks !== undefined && real.length < def.minBlocks) {
    issues.push({ ...at, severity: 'error', code: 'below-min-blocks', message: `"${def.title}" needs at least ${def.minBlocks} blocks` });
  }

  for (const type of def.requiredBlocks ?? []) {
    if (!children.some((c) => c.type === type)) {
      issues.push({ ...at, severity: 'error', code: 'required-block-missing', message: `"${def.title}" needs a "${type}" block` });
    }
  }

  if (def.lockedBoilerplate && def.lockedBoilerplate.length > 0) {
    const expected = await contentHash(normaliseBoilerplate(def.lockedBoilerplate));
    const actual = await contentHash(normaliseBoilerplate(boilerplateIn(section)));
    if (expected !== actual) {
      issues.push({ ...at, severity: 'error', code: 'boilerplate-tampered', message: `Locked boilerplate in "${def.title}" was changed or removed` });
    }
  }

  for (const child of children) {
    if ((child.props as Record<string, unknown>)?.placeholder === true) {
      issues.push({ ...at, severity: 'warning', code: 'placeholder-remaining', message: `Placeholder content remains in "${def.title}"`, blockId: child.id });
    }
  }

  if (def.kind === 'procedure') {
    const steps = findBlocks(children, (b) => procedureTypes.includes(b.type));
    if (steps.length === 0) {
      issues.push({ ...at, severity: 'error', code: 'procedure-steps-missing', message: `"${def.title}" needs at least one procedure step` });
    }
  }
  return issues;
}

/**
 * Validates a document against a template.
 *
 * Checks: required sections present; unknown sections; section order; allowed block types;
 * minimum blocks; required block types; locked boilerplate (hash compare); placeholders left in
 * place; procedure steps; property rules (generated, required, max length, pattern, workflow-only
 * fields); and optional block-level validation through `options.registry`.
 */
export async function validateAgainstTemplate(
  doc: BeakDocument,
  template: TemplateDefinition,
  options: ValidateOptions = {}
): Promise<ValidationIssue[]> {
  const issues: ValidationIssue[] = [];
  const procedureTypes = options.procedureBlockTypes ?? DEFAULT_PROCEDURE_BLOCK_TYPES;
  const top = flattenBlocks(doc);
  const sections = top.filter((b) => b.type === 'controlledSection');
  const byTemplateId = new Map<string, Block>();
  for (const section of sections) {
    const tsid = (section.props as Record<string, unknown>).templateSectionId;
    if (typeof tsid === 'string' && tsid) byTemplateId.set(tsid, section);
    else {
      issues.push({
        severity: 'warning',
        code: 'unknown-section',
        message: 'A controlled section has no templateSectionId',
        sectionId: String((section.props as Record<string, unknown>).sectionId ?? ''),
      });
    }
  }

  const known = new Set(template.sections.map((s) => s.templateSectionId));
  for (const [tsid, section] of byTemplateId) {
    if (!known.has(tsid)) {
      issues.push({ severity: 'warning', code: 'unknown-section', message: `Section "${tsid}" is not in the template`, templateSectionId: tsid, sectionId: String((section.props as Record<string, unknown>).sectionId ?? '') });
    }
  }

  let lastIndex = -1;
  for (const def of template.sections) {
    const section = byTemplateId.get(def.templateSectionId);
    if (!section) {
      if (def.required) {
        issues.push({ severity: 'error', code: 'missing-section', message: `Required section "${def.title}" is missing`, templateSectionId: def.templateSectionId });
      }
      continue;
    }
    const index = top.indexOf(section);
    if (index < lastIndex) {
      issues.push({ severity: 'warning', code: 'section-order', message: `Section "${def.title}" is out of template order`, templateSectionId: def.templateSectionId });
    }
    lastIndex = Math.max(lastIndex, index);
    issues.push(...(await checkSection(def, section, procedureTypes)));
  }

  const rules = options.fieldRules ?? template.properties;
  issues.push(...validateProperties(doc.properties, rules, { fromWorkflow: options.fromWorkflow }));

  if (options.registry) {
    for (const issue of options.registry.validate(top)) {
      issues.push({ severity: issue.severity, code: issue.code, message: issue.message, blockId: issue.blockId });
    }
  }
  return issues;
}
