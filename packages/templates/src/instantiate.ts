/**
 * Instantiating a published template into a document, and building policy contexts.
 *
 * @module
 */

import type { Block } from '@amusendame/beakblock-core';
import type { BeakDocument, DocumentProperties, DocumentSection, PageSetup } from '@amusendame/beakblock-schema';
import { createDefaultNumbering, createDefaultStyleSheet } from '@amusendame/beakblock-schema';
import { ALL_CAPABILITIES } from '@amusendame/beakblock-permissions';
import type { Capability, PolicyContext } from '@amusendame/beakblock-permissions';

import { TemplateError } from './authoring';
import { cloneDeep, cloneWithNewIds, defaultFooterBlocks, defaultHeaderBlocks, findBlocks, newId, paragraph } from './blocks';
import type { SectionAssignments, TemplateDefinition, TemplateSectionDefinition } from './types';

/** Options for {@link instantiateDocument}. */
export interface InstantiateOptions {
  /** Document id. Generated when omitted. */
  documentId?: string;
  /** Document properties entered by the author (title, owner, lab, ...). */
  properties: DocumentProperties;
  /** Document number generated by the QMS service. Required when the `docNumber` rule is `generated`. */
  docNumber?: string;
  /** Owner of each template section, keyed by templateSectionId. Required for required sections. */
  assignments: SectionAssignments;
}

/**
 * Capabilities an owner holds on their own section (contract section 4, roadmap 5F). Owners can change
 * table structure in their section. Mandatory-column and approved-value rights are withheld.
 */
export const OWNER_GRANTS: readonly Capability[] = [
  'section.editText',
  'section.insertBlock',
  'section.deleteBlock',
  'section.changeStyle',
  'table.editStructure',
  // The owner accepts or rejects tracked changes (including AI proposals) in their own section.
  'revision.accept',
  'revision.reject',
];

/** Capabilities of a quality manager on uncontrolled content and section structure. */
export const QUALITY_MANAGER_GRANTS: readonly Capability[] = [
  'document.editUncontrolled',
  'section.rename',
  'section.move',
  'section.moveContentOut',
  'table.editStructure',
  'table.editMandatoryColumns',
  'revision.accept',
  'revision.reject',
];

/** Sets the lock marker on template boilerplate (validation hash-checks these blocks). */
function markBoilerplate(blocks: Block[], templateSectionId: string): Block[] {
  return blocks.map((block) => ({
    ...block,
    props: { ...block.props, lockedBy: 'template', templateSectionId },
  }));
}

/** Marks starter content so validation can warn about placeholders left in the document. */
function markPlaceholder(blocks: Block[]): Block[] {
  return blocks.map((block) => ({ ...block, props: { ...block.props, placeholder: true } }));
}

function controlledSectionBlock(template: TemplateDefinition, def: TemplateSectionDefinition, assignment: { ownerName: string } | undefined): Block {
  const boilerplate = markBoilerplate(cloneWithNewIds(def.lockedBoilerplate ?? []), def.templateSectionId);
  const placeholder = markPlaceholder(cloneWithNewIds(def.placeholder ?? []));
  const children = [...boilerplate, ...placeholder];
  return {
    id: newId('blk'),
    type: 'controlledSection',
    props: {
      sectionId: newId('sec'),
      templateSectionId: def.templateSectionId,
      policyRef: `${template.id}@${template.version}/${def.templateSectionId}`,
      required: def.required,
      allowedBlocks: def.allowedBlocks ?? null,
      title: def.title,
      ownerName: assignment?.ownerName ?? null,
      workflowState: 'draft',
      locked: false,
    },
    children: children.length > 0 ? children : [paragraph('')],
  };
}

/**
 * Creates a document from a published template.
 *
 * Each template section becomes one `controlledSection` (new `sectionId`, `draft` state) containing its
 * locked boilerplate and placeholder. Header and footer carry DOCPROPERTY and PAGE fields. Consecutive
 * sections that share a page master share a document section.
 *
 * @throws {TemplateError} when the template is not published, a required section has no owner,
 *   or the generated document number is missing or conflicts with the entered one
 */
export function instantiateDocument(template: TemplateDefinition, options: InstantiateOptions): BeakDocument {
  if (template.status !== 'published') {
    throw new TemplateError('not-published', `Template "${template.id}" must be published before it is instantiated`);
  }
  for (const def of template.sections) {
    if (def.required && !options.assignments[def.templateSectionId]) {
      throw new TemplateError('missing-assignment', `Required section "${def.templateSectionId}" has no owner`);
    }
  }
  const generated = template.properties.docNumber?.generated === true;
  if (generated) {
    if (!options.docNumber) throw new TemplateError('generated-missing', 'The QMS service must supply the generated document number');
    if (options.properties.docNumber && options.properties.docNumber !== options.docNumber) {
      throw new TemplateError('generated-readonly', 'The document number is generated and read-only');
    }
  }
  const docNumber = options.docNumber ?? options.properties.docNumber ?? '';
  const revision = options.properties.revision ?? '0';
  const documentId = options.documentId ?? newId('doc');

  // Group consecutive sections by page master.
  const groups: Array<{ master: 'default' | 'landscape'; defs: TemplateSectionDefinition[] }> = [];
  for (const def of template.sections) {
    const master = def.pageMaster ?? 'default';
    const last = groups[groups.length - 1];
    if (last && last.master === master) last.defs.push(def);
    else groups.push({ master, defs: [def] });
  }

  const sections: DocumentSection[] = groups.map((group, index) => {
    const pageSetup: PageSetup = cloneDeep(
      group.master === 'landscape' && template.pageMasters.landscape ? template.pageMasters.landscape : template.pageMasters.default
    );
    const blocks = group.defs.map((def) =>
      controlledSectionBlock(template, def, options.assignments[def.templateSectionId])
    );
    return {
      id: `${documentId}-sec-${index + 1}`,
      pageSetup,
      headers: { default: template.header ? cloneWithNewIds(template.header) : defaultHeaderBlocks({ docNumber, revision, title: options.properties.title }) },
      footers: { default: template.footer ? cloneWithNewIds(template.footer) : defaultFooterBlocks() },
      blocks,
    };
  });

  return {
    schemaVersion: 2,
    id: documentId,
    properties: {
      ...cloneDeep(options.properties),
      docNumber,
      revision,
      custom: {
        ...(options.properties.custom ?? {}),
        templateId: template.id,
        templateVersion: String(template.version),
        documentType: template.documentType,
      },
    },
    styles: cloneDeep(template.styles ?? createDefaultStyleSheet()),
    numbering: cloneDeep(template.numbering ?? createDefaultNumbering()),
    sections,
  };
}

/** Top-level and nested controlled section blocks of a document, in order. */
function allSectionBlocks(doc: BeakDocument): Block[] {
  return findBlocks(doc.sections.flatMap((s) => s.blocks), (b) => b.type === 'controlledSection');
}

/**
 * Builds the permissions `PolicyContext` for one principal.
 *
 * - The assigned owner of a section gets `OWNER_GRANTS` on that section only.
 * - Approved sections are listed in `lockedSections`, so nobody edits them through the client.
 * - `system` receives every capability. `qualityManager` receives `QUALITY_MANAGER_GRANTS` as default grants.
 * - Required sections get no `section.delete` grant, so nobody can delete them.
 *
 * `assignments` is keyed by templateSectionId. The section's current state comes from the document.
 */
export function buildPolicyContext(
  doc: BeakDocument,
  assignments: SectionAssignments,
  userId: string,
  roles: string[]
): PolicyContext {
  const sectionGrants: Record<string, Capability[]> = {};
  const lockedSections: string[] = [];
  for (const block of allSectionBlocks(doc)) {
    const props = block.props as Record<string, unknown>;
    const sectionId = String(props.sectionId ?? '');
    if (!sectionId) continue;
    const tsid = typeof props.templateSectionId === 'string' ? props.templateSectionId : '';
    if (props.workflowState === 'approved') lockedSections.push(sectionId);
    if (tsid && assignments[tsid]?.ownerId === userId) sectionGrants[sectionId] = [...OWNER_GRANTS];
  }
  const defaultGrants: Capability[] = [];
  if (roles.includes('system')) defaultGrants.push(...ALL_CAPABILITIES);
  else if (roles.includes('qualityManager')) defaultGrants.push(...QUALITY_MANAGER_GRANTS);
  return { userId, roles: [...roles], sectionGrants, defaultGrants, lockedSections };
}
